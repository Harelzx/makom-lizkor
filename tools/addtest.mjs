import { chromium } from "playwright"
const S = process.argv[2]
const b = await chromium.launch({ args: ["--enable-gpu", "--use-angle=metal"] })
const p = await (await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 })).newPage()
p.on("pageerror", (e) => console.log("ERR", String(e)))
await p.goto("http://localhost:5191/")
await p.evaluate(() => localStorage.setItem("makom-lizkor:v2-seen", "1"))
await p.reload()
await p.waitForTimeout(2500)
await p.getByRole("button", { name: "אל הבוקר" }).click()
await p.waitForTimeout(9000)
await p.evaluate(() => (location.hash = "#/place/community-kfar-aza"))
await p.waitForTimeout(4500)
await p.screenshot({ path: `${S}/flowers.png`, clip: { x: 300, y: 250, width: 600, height: 400 } })
await p
  .getByRole("button", { name: /הוספת מקום/ })
  .first()
  .click()
await p.waitForTimeout(1200)
await p.getByRole("button", { name: "סימון על המפה" }).click()
await p.waitForTimeout(600)
await p.mouse.click(180, 760)
await p.waitForTimeout(500)
console.log("bar:", await p.locator("[role=status]").last().innerText())
await p.getByRole("button", { name: "הסרת הסיכה" }).click()
await p.waitForTimeout(400)
console.log("pin after remove:", await p.locator(".draft-pin").count())
await p.mouse.click(200, 720)
await p.waitForTimeout(400)
await p.getByRole("button", { name: "זה המקום" }).click()
await p.waitForTimeout(800)
console.log("dialog alert has remove:", await p.getByRole("button", { name: "הסרת הסיכה" }).count())
await p.getByRole("button", { name: "המשך" }).click()
await p.waitForTimeout(600)
await p.getByLabel("שם המקום").fill("בדיקה")
await p.getByLabel("קישור לאתר הנצחה (לא חובה)").fill("https://www.example.co.il/page")
console.log("link value:", await p.getByLabel("קישור לאתר הנצחה (לא חובה)").inputValue())
await p.screenshot({ path: `${S}/linkfield.png` })
await b.close()
