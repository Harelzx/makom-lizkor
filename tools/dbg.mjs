import { chromium } from "playwright"
const [w, h] = process.argv.slice(2)
const b = await chromium.launch({ args: ["--enable-gpu", "--use-angle=metal"] })
const ctx = await b.newContext({ viewport: { width: +w, height: +h }, isMobile: +w < 600, hasTouch: +w < 600 })
const p = await ctx.newPage()
p.on("pageerror", (e) => console.log("PAGEERROR", e.stack?.split("\n").slice(0, 6).join("\n")))
await p.goto("http://localhost:5190/")
await p.evaluate(() => localStorage.setItem("makom-lizkor:v2-seen", "1"))
await p.reload()
await p.waitForTimeout(2000)
await p.getByRole("button", { name: "אל הבוקר" }).click()
await p.waitForTimeout(8000)
await p.evaluate(() => document.querySelector('[aria-label="חיפוש"]')?.click())
await p.waitForTimeout(1500)
console.log(await p.evaluate(() => document.body.innerText.slice(0, 200)))
await b.close()
