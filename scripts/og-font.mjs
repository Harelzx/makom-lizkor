// The share image's font, embedded in the Worker (L4): Heebo's Hebrew and Latin subsets at the site's two weights,
// unpacked from @fontsource's WOFF files into plain TrueType (the renderer reads sfnt fonts), written as one module.
// Run after bumping @fontsource/heebo: node scripts/og-font.mjs
import { readFileSync, writeFileSync } from "node:fs"
import { inflateSync } from "node:zlib"

const files = ["hebrew-500", "hebrew-700", "latin-500", "latin-700"].map(
  (n) => `node_modules/@fontsource/heebo/files/heebo-${n}-normal.woff`,
)

/** WOFF 1.0 to sfnt: each table inflated when it was compressed, laid out again with the sfnt directory. */
export function woffToSfnt(woff) {
  const v = new DataView(woff.buffer, woff.byteOffset, woff.byteLength)
  if (v.getUint32(0) !== 0x774f4646) throw new Error("not a WOFF file")
  const flavor = v.getUint32(4)
  const n = v.getUint16(12)
  const tables = []
  for (let i = 0; i < n; i++) {
    const at = 44 + i * 20
    const [tag, offset, compLength, origLength, checksum] = [0, 4, 8, 12, 16].map((k) => v.getUint32(at + k))
    const raw = woff.subarray(offset, offset + compLength)
    tables.push({ tag, checksum, data: compLength < origLength ? inflateSync(raw) : raw })
  }
  const pow = 2 ** Math.floor(Math.log2(n))
  let size = 12 + 16 * n
  for (const t of tables) size += (t.data.length + 3) & ~3
  const out = new Uint8Array(size)
  const o = new DataView(out.buffer)
  o.setUint32(0, flavor)
  o.setUint16(4, n)
  o.setUint16(6, pow * 16)
  o.setUint16(8, Math.log2(pow))
  o.setUint16(10, n * 16 - pow * 16)
  let offset = 12 + 16 * n
  tables.forEach((t, i) => {
    const at = 12 + i * 16
    o.setUint32(at, t.tag)
    o.setUint32(at + 4, t.checksum)
    o.setUint32(at + 8, offset)
    o.setUint32(at + 12, t.data.length)
    out.set(t.data, offset)
    offset += (t.data.length + 3) & ~3
  })
  return out
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const fonts = files.map((f) => Buffer.from(woffToSfnt(readFileSync(f))).toString("base64"))
  writeFileSync(
    "worker/lib/og-font.ts",
    `// Generated by scripts/og-font.mjs from @fontsource/heebo (SIL Open Font License, public/licenses/fonts/Heebo-OFL.txt).\n` +
      `// Heebo 500 and 700, Hebrew and Latin subsets, as TrueType in base64. Don't edit by hand.\n` +
      `export const OG_FONTS = [\n${fonts.map((f) => `  "${f}",`).join("\n")}\n]\n`,
  )
  console.log(`worker/lib/og-font.ts: ${fonts.reduce((s, f) => s + f.length, 0)} base64 characters`)
}
