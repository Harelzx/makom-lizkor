// The curated fixtures (phase 7, task 2): each place of places.json as the record a moderator would send to
// POST /api/admin/places, with a source for every field (spec 3, 9), its photos by file name until the importer
// uploads them. build-data writes it to fixtures/curated.json, outside src/ and public/, so no bundle ever carries it.
//
// Sources are recorded as the research recorded them (adviser a50): coordinates from OSM (ODbL), Wikidata (CC0) or
// set by hand ("manual", never relabelled a survey); the summary is the operator's own writing; each link the text
// rests on is a web source; each photo is its Commons file under its licence; a community's return rests on its
// research's links. No source here was read on a recorded day except the return research (revival.json's as_of), so
// the others carry the date data-src/ was last committed, marked approximate.

const COORD_LICENSE = { osm: "ODbL-1.0", wikidata: "CC0-1.0" }

/** @param {any[]} places places.json @param {{ dataSrcDate: string, revivalAsOf: string }} dates */
export function curatedFixtures(places, { dataSrcDate, revivalAsOf }) {
  const repo = { retrieved_at: dataSrcDate, retrieved_approx: true }
  const records = places.map((p) => ({
    id: p.id,
    kind: p.kind,
    name_he: p.name_he,
    lat: p.lat,
    lng: p.lng,
    precision: p.precision,
    place_he: p.place_he,
    summary_he: p.summary_he,
    curated: {
      established: p.established,
      links: p.links,
      coord_source: p.coord_source,
      coord_source_url: p.coord_source_url,
      region: p.region,
      revival: p.revival,
    },
    photos: p.photos,
    sources: [
      { field: "coords", source: p.coord_source, license: COORD_LICENSE[p.coord_source], url: p.coord_source_url, ...repo },
      { field: "text", source: "operator", retrieved_approx: false },
      ...p.links.map((l) => ({ field: "text", source: "web", url: l.url, ...repo })),
      ...p.photos.map((ph, i) => ({ field: "photo", photo_idx: i, source: "commons", license: ph.license, url: ph.commons_url, ...repo })),
      ...(p.revival
        ? p.revival.sources.length
          ? p.revival.sources.map((s) => ({
              field: "revival",
              source: "web",
              url: s.url,
              retrieved_at: revivalAsOf,
              retrieved_approx: false,
            }))
          : [{ field: "revival", source: "operator", retrieved_approx: false }]
        : []),
    ],
  }))
  // As it reads back from the file: no key left holding undefined.
  return JSON.parse(
    JSON.stringify({
      note: "Generated by scripts/build-data.mjs; never edit by hand. retrieved_at is data-src's last commit date (approximate) except a community's return, dated by revival.json's as_of.",
      data_src_date: dataSrcDate,
      revival_as_of: revivalAsOf,
      places: records,
    }),
  )
}
