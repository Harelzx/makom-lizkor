import { expect, test } from "./fixtures"
import { audit } from "./axe"

test.use({ reducedMotion: "reduce" })

test("@phone a visitor selects and corrects a point using only the keyboard in the form", async ({ page, browserName }) => {
  const tab = browserName === "webkit" ? "Alt+Tab" : "Tab"
  await page.goto("/")
  await page.getByRole("button", { name: "דילוג", exact: true }).click()
  await page.getByRole("button", { name: "הוספת מקום", exact: true }).click()
  const mapButton = page.getByRole("button", { name: "סימון על המפה", exact: true })
  await expect(mapButton).toBeFocused({ timeout: 20000 })
  await page.keyboard.press(tab)
  await expect(page.getByRole("button", { name: "המיקום הנוכחי שלי", exact: true })).toBeFocused()
  await page.keyboard.press(tab)
  const summary = page.locator("summary").filter({ hasText: "הזנת נקודה במקלדת" })
  await expect(summary).toBeFocused()
  await page.keyboard.press("Enter")
  await page.keyboard.press(tab)
  const lat = page.getByRole("textbox", { name: "קו רוחב", exact: true })
  const lng = page.getByRole("textbox", { name: "קו אורך", exact: true })
  await expect(lat).toBeFocused()
  await page.keyboard.type("NaN")
  await page.keyboard.press(tab)
  await expect(lng).toBeFocused()
  await page.keyboard.type("34.52439")
  await page.keyboard.press("Enter")
  await expect(lat).toBeFocused()
  await expect(page.getByRole("alert").filter({ hasText: "כתבו קו רוחב" })).toBeVisible()
  await expect(page.getByRole("heading", { name: "איפה המקום?", exact: true })).toBeVisible()
  await audit(page)
  await page.keyboard.press("ControlOrMeta+A")
  await page.keyboard.type("31.46415")
  await page.keyboard.press("Enter")
  await expect(summary).toBeFocused()
  await expect(page.getByText(/סומן מיקום/)).toContainText("31.46415")
  await expect(page.getByText(/סומן מיקום/)).toContainText("34.52439")
  await expect(lat).toBeHidden()
  await page.getByRole("button", { name: "המשך", exact: true }).press("Enter")
  await expect(page.getByRole("heading", { name: "מה יש שם?", exact: true })).toBeFocused()
  await page.getByRole("button", { name: "חזרה", exact: true }).press("Enter")
  await expect(page.getByText(/סומן מיקום/)).toContainText("31.46415")
  await expect(page.getByText(/סומן מיקום/)).toContainText("34.52439")
})

test("@phone typed coordinates do not write a proposal before deliberate submission", async ({ page }) => {
  await page.goto("/")
  await page.getByRole("button", { name: "דילוג", exact: true }).click()
  await page.getByRole("button", { name: "הוספת מקום", exact: true }).click()
  await expect(page.getByRole("heading", { name: "איפה המקום?", exact: true })).toBeVisible({ timeout: 20000 })
  const writes: string[] = []
  page.on("request", (request) => {
    if (request.method() !== "GET" && request.postData()?.includes("31.46415")) writes.push(new URL(request.url()).pathname)
  })
  await page.locator("summary").filter({ hasText: "הזנת נקודה במקלדת" }).press("Enter")
  await page.getByRole("textbox", { name: "קו רוחב", exact: true }).fill("31.46415")
  await page.getByRole("textbox", { name: "קו אורך", exact: true }).fill("34.52439")
  await page.getByRole("button", { name: "שמירת הנקודה", exact: true }).press("Enter")
  await expect(page.getByText(/סומן מיקום/)).toBeVisible()
  await page.getByRole("button", { name: "סגירה", exact: true }).press("Enter")
  await page.getByRole("button", { name: "הוספת מקום", exact: true }).click()
  await expect(page.getByRole("heading", { name: "איפה המקום?", exact: true })).toBeVisible()
  await expect(page.getByText(/סומן מיקום/)).toHaveCount(0)
  expect(writes).toEqual([])
  await audit(page)
})
