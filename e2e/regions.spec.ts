import { test, expect } from "./fixtures"
import { audit } from "./axe"

test.use({ reducedMotion: "reduce" })
for (const width of [390, 1280])
  test(`regional groups, search and saved visits work together at ${width}px`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    await page.goto("/")
    await page.getByRole("button", { name: "דילוג", exact: true }).click()
    await expect(page.getByRole("button", { name: "על הפרויקט", exact: true })).toBeVisible({ timeout: 20_000 })
    if (width < 768) await page.getByRole("button", { name: "הצגת המקומות", exact: true }).click()
    const panel = page.locator("#places")
    const envelope = panel.getByRole("button", { name: /^עוטף עזה/ })
    const north = panel.getByRole("button", { name: /^הצפון/ })
    const golan = panel.getByRole("button", { name: /^רמת הגולן/ })
    await expect(panel.getByRole("heading", { level: 3 })).toHaveCount(9)
    await expect(envelope).toHaveAttribute("aria-expanded", "true")
    await north.press("Enter")
    await expect(north).toHaveAttribute("aria-expanded", "true")
    await expect(envelope).toHaveAttribute("aria-expanded", "false")
    await expect(panel.getByRole("list", { name: "הצפון", exact: true }).getByRole("button")).toHaveCount(6)
    await golan.click()
    await expect(north).toHaveAttribute("aria-expanded", "false")
    await expect(golan).toHaveAttribute("aria-expanded", "true")
    const query = panel.getByRole("searchbox", { name: "חיפוש", exact: true })
    await query.fill("מצפה")
    // Matching records in every region remain visible, including ones in previously closed groups.
    await expect(panel.getByRole("button", { name: /מצפה עמית/ })).toBeVisible()
    await expect(panel.getByRole("button", { name: /מצפה עמיחי ומצפה עמישר/ })).toBeVisible()
    await query.fill("")
    await expect(golan).toHaveAttribute("aria-expanded", "true")
    await expect(panel.getByRole("button", { name: /מצפה עמיחי ומצפה עמישר/ })).toBeVisible()
    await audit(page)
    await panel.getByRole("button", { name: /מצפה עמיחי ומצפה עמישר/ }).click()
    await page.getByRole("button", { name: "שמירה לביקור", exact: true }).click()
    await page.getByRole("button", { name: "כל המקומות", exact: true }).click()
    await page.getByRole("button", { name: "שמורים לביקור", exact: true }).click()
    await expect(panel.getByRole("heading", { level: 3 })).toHaveCount(1)
    await expect(panel.getByRole("heading", { name: /^רמת הגולן/ })).toBeVisible()
    await expect(panel.getByRole("button", { name: /מצפה עמיחי ומצפה עמישר/ })).toBeVisible()
    await expect(panel.getByRole("button", { name: /מצפה עמית/ })).toHaveCount(0)
  })
